-- Poker Settler — Supabase schema
--
-- Run this in the SQL editor of a Supabase project to stand up (or upgrade) a
-- database that matches production. Safe to re-run: every statement is
-- idempotent.
--
-- Before using the app, enable anonymous sign-ins in the Supabase dashboard:
-- Authentication -> Sign In / Providers -> "Allow anonymous sign-ins".
--
-- Access model: every row belongs to a group. A device signs in anonymously,
-- then joins a group by invite code. Row level security only lets a user touch
-- rows of groups they are a member of, so groups never see each other's data.

create table if not exists games (
  code         text primary key,
  buy_in       integer not null,
  players      jsonb not null default '[]',
  settled      boolean not null default false,
  created_at   timestamptz not null default now(),
  title        text,
  password     text
);

create table if not exists known_players (
  id           bigint generated by default as identity primary key,
  name         text not null
);

create table if not exists groups (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  invite_code  text not null unique,
  created_at   timestamptz not null default now()
);

create table if not exists group_members (
  group_id     uuid not null references groups(id) on delete cascade,
  user_id      uuid not null default auth.uid(),
  joined_at    timestamptz not null default now(),
  primary key (group_id, user_id)
);

-- Columns added after the original tables shipped. Kept as explicit migrations
-- so an older database can be brought up to date by re-running this file.
alter table games add column if not exists title    text;
alter table games add column if not exists password text;
alter table games add column if not exists is_test  boolean not null default false;
alter table games         add column if not exists group_id uuid references groups(id) on delete cascade;
alter table known_players add column if not exists group_id uuid references groups(id) on delete cascade;

create index if not exists games_group_id_idx         on games(group_id);
create index if not exists known_players_group_id_idx on known_players(group_id);
create index if not exists group_members_user_id_idx  on group_members(user_id);

-- Rows that predate groups all go into one starting group. Its invite code is
-- returned by the last statement of this file, so the existing crew can rejoin.
do $$
declare
  legacy_group uuid;
begin
  if exists (select 1 from games where group_id is null)
     or exists (select 1 from known_players where group_id is null) then
    insert into groups (name, invite_code)
    values ('Original crew', upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10)))
    returning id into legacy_group;
    update games         set group_id = legacy_group where group_id is null;
    update known_players set group_id = legacy_group where group_id is null;
  end if;
end $$;

alter table games         alter column group_id set not null;
alter table known_players alter column group_id set not null;

-- Membership check used by every policy. security definer so it can read
-- group_members without tripping that table's own policies.
create or replace function is_group_member(target_group uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from group_members
    where group_id = target_group and user_id = auth.uid()
  );
$$;

-- Creating and joining go through functions so a client can never insert a
-- membership row for a group it has not proven access to.
create or replace function create_group(group_name text)
returns groups
language plpgsql
security definer
set search_path = public
as $$
declare
  new_group groups;
begin
  if auth.uid() is null then
    raise exception 'not signed in';
  end if;
  if length(trim(group_name)) = 0 then
    raise exception 'group name is required';
  end if;
  insert into groups (name, invite_code)
  values (trim(group_name), upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10)))
  returning * into new_group;
  insert into group_members (group_id, user_id) values (new_group.id, auth.uid());
  return new_group;
end;
$$;

create or replace function join_group(code text)
returns groups
language plpgsql
security definer
set search_path = public
as $$
declare
  target groups;
begin
  if auth.uid() is null then
    raise exception 'not signed in';
  end if;
  select * into target from groups where invite_code = upper(trim(code));
  if not found then
    raise exception 'invalid invite code';
  end if;
  insert into group_members (group_id, user_id)
  values (target.id, auth.uid())
  on conflict do nothing;
  return target;
end;
$$;

revoke all on function create_group(text) from public, anon;
revoke all on function join_group(text)   from public, anon;
grant execute on function create_group(text) to authenticated;
grant execute on function join_group(text)   to authenticated;
grant execute on function is_group_member(uuid) to authenticated;

-- Replace whatever policies exist (including the old fully open ones).
do $$
declare
  existing record;
begin
  for existing in
    select policyname, tablename from pg_policies
    where schemaname = 'public'
      and tablename in ('games', 'known_players', 'groups', 'group_members')
  loop
    execute format('drop policy %I on public.%I', existing.policyname, existing.tablename);
  end loop;
end $$;

alter table games         enable row level security;
alter table known_players enable row level security;
alter table groups        enable row level security;
alter table group_members enable row level security;

create policy "members read"   on games for select to authenticated using (is_group_member(group_id));
create policy "members insert" on games for insert to authenticated with check (is_group_member(group_id));
create policy "members update" on games for update to authenticated using (is_group_member(group_id)) with check (is_group_member(group_id));
create policy "members delete" on games for delete to authenticated using (is_group_member(group_id));

create policy "members read"   on known_players for select to authenticated using (is_group_member(group_id));
create policy "members insert" on known_players for insert to authenticated with check (is_group_member(group_id));
create policy "members update" on known_players for update to authenticated using (is_group_member(group_id)) with check (is_group_member(group_id));
create policy "members delete" on known_players for delete to authenticated using (is_group_member(group_id));

create policy "members read" on groups for select to authenticated using (is_group_member(id));

create policy "read own membership"  on group_members for select to authenticated using (user_id = auth.uid());
create policy "leave own membership" on group_members for delete to authenticated using (user_id = auth.uid());

-- Realtime: powers live sync of a game across everyone's phones. Realtime
-- applies the policies above using each subscriber's login.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'games'
  ) then
    alter publication supabase_realtime add table games;
  end if;
end $$;

-- The starting group's invite code, if this run created one.
select name, invite_code from groups order by created_at limit 5;
